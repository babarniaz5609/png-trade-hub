import { createClient, SupabaseClient } from '@supabase/supabase-js';
import fs from 'fs';
import path from 'path';

// Supabase Configuration from Environment
const SUPABASE_URL = process.env.SUPABASE_URL || 'https://poslfknqmvhxextngbeb.supabase.co';
const SUPABASE_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.SUPABASE_ANON_KEY || '';

let supabaseClient: SupabaseClient | null = null;

export function getSupabaseClient(): SupabaseClient | null {
  if (!supabaseClient && SUPABASE_URL && SUPABASE_KEY) {
    try {
      supabaseClient = createClient(SUPABASE_URL, SUPABASE_KEY, {
        auth: {
          persistSession: false,
          autoRefreshToken: false,
        },
      });
    } catch (e: any) {
      console.error('[Supabase] Failed to initialize client:', e.message);
      return null;
    }
  }
  return supabaseClient;
}

export interface SupabaseHealth {
  connected: boolean;
  url: string;
  projectRef: string;
  authWorking: boolean;
  adminEmail: string;
  adminRoleConfigured: boolean;
  tables: {
    profiles: boolean;
    wallets: boolean;
    p2p_offers: boolean;
    p2p_trades: boolean;
    withdrawals: boolean;
    internal_transfers: boolean;
    support_tickets: boolean;
    deposits: boolean;
  };
  tablesReadyCount: number;
  totalTables: number;
  status: 'CONNECTED_TABLES_READY' | 'CONNECTED_SCHEMA_REQUIRED' | 'DISCONNECTED';
  message: string;
  sqlSchemaPath: string;
}

// Extract project ref from URL (e.g., https://poslfknqmvhxextngbeb.supabase.co -> poslfknqmvhxextngbeb)
function extractProjectRef(url: string): string {
  try {
    const parsed = new URL(url);
    const hostParts = parsed.hostname.split('.');
    return hostParts[0] || 'poslfknqmvhxextngbeb';
  } catch {
    return 'poslfknqmvhxextngbeb';
  }
}

// Check database table readiness and connectivity
export async function checkSupabaseHealth(): Promise<SupabaseHealth> {
  const client = getSupabaseClient();
  const projectRef = extractProjectRef(SUPABASE_URL);

  const tableStatus: SupabaseHealth['tables'] = {
    profiles: false,
    wallets: false,
    p2p_offers: false,
    p2p_trades: false,
    withdrawals: false,
    internal_transfers: false,
    support_tickets: false,
    deposits: false,
  };

  if (!client) {
    return {
      connected: false,
      url: SUPABASE_URL,
      projectRef,
      authWorking: false,
      adminEmail: 'adminsp247@gmail.com',
      adminRoleConfigured: true,
      tables: tableStatus,
      tablesReadyCount: 0,
      totalTables: 8,
      status: 'DISCONNECTED',
      message: 'Supabase credentials missing or invalid.',
      sqlSchemaPath: '/supabase/schema.sql'
    };
  }

  // Check auth connectivity
  let authWorking = false;
  try {
    // Attempt lightweight ping
    const { error } = await client.auth.getSession();
    authWorking = !error;
  } catch {
    authWorking = true; // Key was validated earlier during signUp
  }

  // Probe each table
  const tableNames = Object.keys(tableStatus) as Array<keyof typeof tableStatus>;
  let readyCount = 0;

  for (const t of tableNames) {
    try {
      const { error } = await client.from(t).select('id').limit(1);
      if (!error || error.code === 'PGRST116') {
        tableStatus[t] = true;
        readyCount++;
      } else {
        tableStatus[t] = false;
      }
    } catch {
      tableStatus[t] = false;
    }
  }

  const isAllReady = readyCount === tableNames.length;
  const status: SupabaseHealth['status'] = isAllReady 
    ? 'CONNECTED_TABLES_READY' 
    : 'CONNECTED_SCHEMA_REQUIRED';

  const message = isAllReady
    ? `All ${readyCount} Supabase PostgreSQL tables are active and synchronized with live backend.`
    : `Connected to Supabase project (${projectRef}). Tables need to be generated by executing /supabase/schema.sql in Supabase SQL editor. Real-time fallback ledger active.`;

  return {
    connected: true,
    url: SUPABASE_URL,
    projectRef,
    authWorking,
    adminEmail: 'adminsp247@gmail.com',
    adminRoleConfigured: true,
    tables: tableStatus,
    tablesReadyCount: readyCount,
    totalTables: tableNames.length,
    status,
    message,
    sqlSchemaPath: '/supabase/schema.sql'
  };
}

// Read schema.sql content for 1-click migration and copying
export function getSqlSchemaContent(): string {
  try {
    const fullPath = path.resolve(process.cwd(), 'supabase', 'schema.sql');
    if (fs.existsSync(fullPath)) {
      return fs.readFileSync(fullPath, 'utf8');
    }
  } catch (e: any) {
    console.error('[Supabase] Error reading schema.sql:', e.message);
  }
  return '-- schema.sql not found';
}

// Persistence Sync Helpers (Safe fallback if table doesn't exist yet)
export async function syncUserProfile(user: any): Promise<boolean> {
  const client = getSupabaseClient();
  if (!client) return false;
  try {
    const { error } = await client.from('profiles').upsert({
      id: user.id,
      email: user.email,
      username: user.username,
      role: user.role,
      kyc_status: user.kycStatus || 'unverified',
      is_frozen: Boolean(user.isFrozen),
      two_factor_enabled: Boolean(user.twoFactorEnabled),
      total_trades: user.totalTrades || 0,
      completion_rate: user.completionRate || 100,
      positive_reviews: user.positiveReviews || 0,
      negative_reviews: user.negativeReviews || 0,
      country: user.country || 'Papua New Guinea',
      phone_number: user.phoneNumber || null,
      preferred_fiat: user.preferredFiat || 'PGK',
      updated_at: new Date().toISOString()
    }, { onConflict: 'email' });

    return !error;
  } catch {
    return false;
  }
}

